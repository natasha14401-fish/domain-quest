const TOPIC_CODES = { actors: 'a', processes: 'p', data: 'd', rules: 'r', problems: 'x', goals: 'g' }

function unique(list) {
  return [...new Set(list)]
}

function defineScenario(cfg) {
  const topics = {}
  for (const topic of topicOrder) {
    const src = cfg.topics[topic]
    topics[topic] = {
      label: TOPIC_LABELS[topic],
      hints: src.hints ?? DEFAULT_HINTS[topic],
      facts: src.facts.map((text, i) => ({
        id: `${cfg.id}-${TOPIC_CODES[topic]}${i + 1}`,
        text,
      })),
      answers: [
        {
          keys: unique([...(src.keys ?? []), ...GENERIC_KEYS[topic]]),
          text: src.answer,
        },
      ],
    }
  }

  return {
    id: cfg.id,
    title: cfg.title,
    subtitle: cfg.subtitle,
    tone: cfg.tone,
    accent: cfg.accent,
    stakeholder: cfg.stakeholder,
    topics,
    interview: topicOrder.map((topic, i) => ({
      id: `${cfg.id}-i${i + 1}`,
      topic,
      question: cfg.interview?.[topic]?.question ?? DEFAULT_INTERVIEW[topic].question,
      placeholder: cfg.interview?.[topic]?.placeholder ?? DEFAULT_INTERVIEW[topic].placeholder,
    })),
  }
}

